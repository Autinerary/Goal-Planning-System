"""Write the creator's catalog into frontend/lib/avatar3d/character.ts.

    python3 scripts/avatar3d/gen_catalog.py

Rewrites the block between "// <catalog>" and "// </catalog>" from catalog.py,
so the page and the models always agree on ids. (One file, so the library
test can import it with Node alone.)
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import catalog as C  # noqa: E402

TARGET = os.path.join(HERE, "..", "..", "frontend", "lib", "avatar3d", "character.ts")


def items(rows, extra=None):
    out = []
    for r in rows:
        d = {"id": r[0], "label": r[1]}
        if extra:
            d.update(extra(r))
        out.append(d)
    return out


blocks = {
    "HAIRS": items(C.HAIRS),
    "BROWS": items(C.BROWS),
    "BEARDS": items(C.BEARDS),
    "OUTFITS": items([o for o in C.OUTFITS if o[0] != "basics"]),
    "GLASSES": items(C.GLASSES),
    "POSES": items(C.POSES),
    "EYES": items(C.EYES),
    "FACE_SLIDERS": [{"id": f[0], "label": f[1], "area": f[2], "twoWay": bool(f[3]), "downLabel": f[5], "upLabel": f[6]} for f in C.FACE],
    "BODY_SLIDERS": [{"id": b[0], "label": b[1], "downLabel": b[5], "upLabel": b[6]} for b in C.BODY],
    "ENVIRONMENTS": items(C.ENVIRONMENTS, lambda e: {"backdrop": e[5], "light": e[6], "credit": e[4]}),
    "FEATURES": items(C.FEATURES),
    "FACE_PAINTS": items(C.FACE_PAINTS),
    "TATTOOS": items(C.TATTOOS),
}

def ts(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "\\'") + "'"


lines = ["// <catalog> Generated by scripts/avatar3d/gen_catalog.py from catalog.py. Edit there, then run it."]
for name, rows in blocks.items():
    body = "\n".join("  { " + ", ".join(f"{k}: {ts(v)}" for k, v in r.items()) + " }," for r in rows)
    lines.append(f"export const {name} = [\n{body}\n] as const")
lines.append("// </catalog>")
block = "\n".join(lines)

src = open(TARGET).read()
a, b = src.index("// <catalog>"), src.index("// </catalog>") + len("// </catalog>")
open(TARGET, "w").write(src[:a] + block + src[b:])
print("wrote", os.path.relpath(TARGET), {k: len(v) for k, v in blocks.items()})
