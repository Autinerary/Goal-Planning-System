// Copies one-click sign-up's kit (frontend/lib/signupKit.ts: each service's
// steps and the runner that fills them in) to everywhere it runs:
//   chrome-extension/signup-kit.js   the extension (a classic script)
//   desktop/signup-kit.js            the desktop app (Electron)
//   mobile/lib/signupKitSource.ts    the phone app (a string, sent into its web view)
//   frontend/lib/signupKitSource.ts  the server robot (a string, sent into its browser)
//   servicehub-mvp/lib/signupServices.ts  ResourceHub (which services, their names and sites)
//   mobile/lib/signupServices.ts          the phone app's Sign up screen (names, start pages, terms)
// Run with Node's type stripping, from the repo root:
//   node --experimental-strip-types scripts/build-signup-kit.mjs           write them
//   node --experimental-strip-types scripts/build-signup-kit.mjs --check   fail if any is out of date (CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { KIT_VERSION, RECIPES, runContactForm, runSignup } from '../frontend/lib/signupKit.ts'

const root = fileURLToPath(new URL('..', import.meta.url))
const HEAD = '// Generated by scripts/build-signup-kit.mjs from frontend/lib/signupKit.ts. Do not edit; run the script.'

// The runner as plain JavaScript (the types were stripped when it loaded), with the recipes.
const script = `${HEAD}
(function (g) {
  g.AutinerarySignup = {
    version: ${JSON.stringify(KIT_VERSION)},
    recipes: ${JSON.stringify(RECIPES, null, 2).replace(/\n/g, '\n    ')},
    run: ${runSignup.toString().replace(/\n/g, '\n    ')},
    // Local services: their website's contact or booking form.
    contact: ${runContactForm.toString().replace(/\n/g, '\n    ')},
  }
})(typeof self !== 'undefined' ? self : globalThis);
`
const asString = (exportName) => `${HEAD}
// The kit as a script to send into a page: it defines window.AutinerarySignup (run, contact).
export const ${exportName} = ${JSON.stringify(script)}
`

const services = Object.fromEntries(Object.values(RECIPES).map((r) => [r.key, { name: r.name, kind: r.kind, hosts: r.hosts }]))
const hubList = `${HEAD}
// The services one-click sign-up can do, for ResourceHub's Sign me up links (lib/signup.ts).
export const SIGNUP_SERVICES: Record<string, { name: string; kind: 'account' | 'newsletter'; hosts: string[] }> = ${JSON.stringify(services, null, 2)}
`

const phone = Object.fromEntries(Object.values(RECIPES).map((r) => [r.key, { name: r.name, kind: r.kind, start: r.start, terms: r.terms || null, privacy: r.privacy || null, note: r.note || null }]))
const phoneList = `${HEAD}
// The services one-click sign-up can do, for the phone app's Sign up screen (screens/SignupScreen.tsx).
export const SIGNUP_SERVICES: Record<string, { name: string; kind: 'account' | 'newsletter'; start: string; terms: string | null; privacy: string | null; note: string | null }> = ${JSON.stringify(phone, null, 2)}
`

const outputs = {
  'chrome-extension/signup-kit.js': script,
  'desktop/signup-kit.js': script,
  'mobile/lib/signupKitSource.ts': asString('SIGNUP_KIT_SOURCE'),
  'frontend/lib/signupKitSource.ts': asString('SIGNUP_KIT_SOURCE'),
  'servicehub-mvp/lib/signupServices.ts': hubList,
  'mobile/lib/signupServices.ts': phoneList,
}

const check = process.argv.includes('--check')
let stale = 0
for (const [rel, content] of Object.entries(outputs)) {
  const path = `${root}${rel}`
  if (check) {
    // Whitespace aside: Node versions strip types into slightly different spacing.
    const squash = (t) => t.replace(/\s+/g, ' ')
    const same = existsSync(path) && squash(readFileSync(path, 'utf8')) === squash(content)
    if (!same) { stale++; console.error(`out of date: ${rel}`) }
  } else {
    writeFileSync(path, content)
    console.log(`wrote ${rel}`)
  }
}
if (check) {
  if (stale) { console.error('Run: node --experimental-strip-types scripts/build-signup-kit.mjs'); process.exit(1) }
  console.log(`signup kit: ok (${Object.keys(RECIPES).length} services, version ${KIT_VERSION}, ${Object.keys(outputs).length} copies match)`)
}
