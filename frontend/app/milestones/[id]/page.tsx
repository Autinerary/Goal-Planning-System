'use client'

import { useState, useEffect } from 'react'
import { useRouter, useParams } from 'next/navigation'
import Link from 'next/link'
import { BookOpen, ChevronRight, Wrench } from 'lucide-react'
import { useAgentPath } from '../../context/AgentPathContext'
import BackButton from '../../components/BackButton'
import MilestoneRating from '@/app/components/MilestoneRating'
import NormsPrompt from '@/app/components/NormsPrompt'
import SponsoredService from '@/app/components/SponsoredService'
import MilestoneTools from '@/app/components/MilestoneTools'
import TopMistakes from '@/app/components/TopMistakes'
import { toolsFromRecs } from '@/lib/milestoneTools'
import { guidanceFor } from '@/lib/guidanceData'
import { useMilestoneGuidance } from '@/lib/useMilestoneGuidance'


export default function MilestoneDetailView() {
  const params = useParams()
  const router = useRouter()
  const milestoneId = params.id as string
  const { payload, pathPlanning, toolRecommendation } = useAgentPath()
  const [milestone, setMilestone] = useState<any>(null)
  const [loading, setLoading] = useState(true)
  // What to avoid here: the same five the Race view's Avoidance shows (lib/guidanceData.ts).
  const planName = (pathPlanning?.milestones || []).find((m: any) => m.id === milestoneId)?.name || ''
  const { guidance, loading: guidanceLoading, failed: guidanceFailed } = useMilestoneGuidance(
    payload as any,
    planName ? [{ id: milestoneId, name: planName }] : [],
  )

  // Saved completion lives in race_progress (localStorage is only a cache).
  // Without this the page reported "in progress / 0%" for a milestone the user
  // had already ticked off on the trail.
  const [isComplete, setIsComplete] = useState(false)
  useEffect(() => {
    try {
      const s = localStorage.getItem('completedMilestoneIds')
      if (s) setIsComplete(new Set(JSON.parse(s)).has(milestoneId))
    } catch {}
    fetch('/api/me/progress', { credentials: 'include' })
      .then((r) => (r.ok ? r.json() : null))
      .then((d) => {
        if (!d) return
        const rows = d.progress || d.rows || d || []
        if (!Array.isArray(rows)) return
        setIsComplete(
          rows.some((r: any) => r.kind === 'completed' && r.milestone_id === milestoneId)
        )
      })
      .catch(() => {})
  }, [milestoneId])

  useEffect(() => {
    // Prefer the real milestone produced by the path-planning agent. Fall back
    // to the mock catalogue (legacy demo IDs like 'r1c1') and finally to a
    // generic stub so the page never crashes.
    const agentMilestone = (pathPlanning?.milestones || []).find(
      (m: any) => m.id === milestoneId
    )
    if (agentMilestone) {
      // Free first, then the cheapest (lib/milestoneTools.ts toolsFromRecs);
      // the same list, edits and limit of 5 as the Milestone view.
      const agentTools = toolsFromRecs((toolRecommendation?.recommendations || {})[milestoneId])
      // A milestone's own tasks (stored with it since this change); older
      // paths have them only in path planning's flat list.
      const raceMilestone = ((payload?.races || []) as any[])
        .flatMap((r) => (Array.isArray(r?.milestones) ? r.milestones : []))
        .find((m: any) => m?.id === milestoneId)
      const ownTasks: any[] = Array.isArray(raceMilestone?.tasks) && raceMilestone.tasks.length
        ? raceMilestone.tasks
        : ((pathPlanning?.tasks || []) as any[]).filter((t) => t.milestoneId === milestoneId)
      const agentTasks: string[] = ownTasks
        .slice(0, 6)
        .map((t) => t.name || t.title)
      setMilestone({
        id: agentMilestone.id,
        name: agentMilestone.name || agentMilestone.title,
        description: agentMilestone.description || 'Personalised milestone generated by your agents.',
        status: isComplete ? 'completed' : (agentMilestone.status || 'in_progress'),
        progress: isComplete ? 100 : (agentMilestone.progress ?? 0),
        race: agentMilestone.race,
        nextSteps: agentTasks.length ? agentTasks : (agentMilestone.nextSteps || []),
        tools: agentTools,
      })
    } else {
      // No demo catalogue — an unresolved milestone shows a minimal real stub
      // (no fake tools) rather than mock content.
      setMilestone({
        id: milestoneId,
        name: `Milestone: ${milestoneId}`,
        description: 'This milestone is part of your personalized path.',
        status: 'pending',
        tools: [],
      })
    }
    setLoading(false)
  }, [milestoneId, payload, pathPlanning, toolRecommendation, isComplete])

  if (loading) {
    return (
      <div className="flex items-center justify-center min-h-screen surface-veil">
        <div className="text-center">
          <div className="animate-spin rounded-full h-12 w-12 border-b-2 border-cyan-600 mx-auto mb-4"></div>
          <p className="text-slate-600">Loading milestone...</p>
        </div>
      </div>
    )
  }

  if (!milestone) {
    return (
      <div className="flex items-center justify-center min-h-screen surface-veil">
        <div className="text-center">
          <p className="text-slate-600 mb-4">Milestone not found</p>
          <Link href="/races" className="text-cyan-600 underline underline-offset-2">Back to Races</Link>
        </div>
      </div>
    )
  }

  return (
    <div className="min-h-screen p-4 md:p-8 relative overflow-hidden surface-veil">
      {/* Background decorations */}
      <div className="fixed inset-0 overflow-hidden pointer-events-none pref-gamify">
        <div className="absolute top-20 left-10 w-72 h-72 bg-cyan-500/20 rounded-full blur-3xl animate-pulse" style={{ animationDuration: '4s' }} />
        <div className="absolute bottom-20 right-10 w-96 h-96 bg-purple-500/20 rounded-full blur-3xl animate-pulse" style={{ animationDuration: '5s', animationDelay: '1s' }} />
        <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-[600px] h-[600px] bg-pink-500/15 rounded-full blur-3xl animate-pulse" style={{ animationDuration: '6s', animationDelay: '2s' }} />
      </div>
      <div className="relative z-10">
      <div className="max-w-4xl mx-auto">
        {/* Back to wherever this was opened from: the Path's "Open this step"
            leads here too, and this always said "Back to Races". */}
        <BackButton fallback="/races" className="mb-6" />

        {/* Milestone Header Card */}
        <div className="bg-white rounded-2xl border border-slate-200 p-6 md:p-8 mb-6 shadow-sm">
          <div className="flex flex-col md:flex-row md:items-start md:justify-between gap-4">
            <div className="flex-1">
              <div className="flex items-center gap-3 mb-2">
                {milestone.race && (
                  <span className="text-sm px-3 py-1 bg-slate-100 rounded-full text-slate-600">
                    {milestone.race}
                  </span>
                )}
              </div>
              <h1 className="text-2xl sm:text-3xl font-bold text-slate-900 mb-3">{milestone.name}</h1>
              <p className="text-slate-600">{milestone.description}</p>
            </div>

            {/* Stats for recommended choices */}
            {milestone.successRate && (
              <div className="bg-emerald-50 rounded-xl p-4 text-center min-w-[140px]">
                <div className="text-3xl font-bold text-emerald-600">{milestone.successRate}%</div>
                <div className="text-sm text-emerald-700">Success Rate</div>
                <div className="text-xs text-slate-500 mt-1">{milestone.attempts?.toLocaleString()} attempts</div>
              </div>
            )}
          </div>

          {/* Progress bar for current milestone */}
          {milestone.progress !== undefined && (
            <div className="mt-6">
              <div className="flex justify-between text-sm mb-2">
                <span className="text-slate-600">Progress</span>
                <span className="font-bold text-slate-900">{milestone.progress}%</span>
              </div>
              <div className="h-3 bg-slate-100 rounded-full overflow-hidden">
                <div 
                  className="h-full bg-indigo-600 hover:bg-indigo-700 active:bg-indigo-800 rounded-full transition-all"
                  style={{ width: `${milestone.progress}%` }}
                />
              </div>
            </div>
          )}

          {/* Next Steps */}
          {milestone.nextSteps && (
            <div className="mt-6 pt-6 border-t border-slate-200">
              <h3 className="font-semibold text-slate-900 mb-3">Next Steps:</h3>
              <div className="space-y-2">
                {milestone.nextSteps.map((step: string, idx: number) => (
                  <div key={idx} className="flex items-center gap-3">
                    <div className={`w-6 h-6 rounded-full flex items-center justify-center text-xs font-bold ${
                      idx === 0 ? 'bg-amber-400 text-white' : 'bg-slate-200 text-slate-600'
                    }`}>
                      {idx + 1}
                    </div>
                    <span className={idx === 0 ? 'font-medium' : 'text-slate-600'}>{step}</span>
                  </div>
                ))}
              </div>
              <div className="mt-3 flex items-start gap-2 p-3 bg-sky-50 border border-sky-200 rounded-xl">
                <span className="text-base mt-0.5">📅</span>
                <p className="text-sm text-sky-800">
                  These have been added to your <Link href="/calendar" className="font-bold underline hover:text-sky-600">Calendar</Link>, and can be seen by clicking the Calendar View below!
                </p>
              </div>
            </div>
          )}

          <TopMistakes
            className="mt-6"
            milestoneId={milestone.id}
            guidance={guidanceFor(guidance, milestone.id, milestone.name)}
            loading={guidanceLoading}
            failed={guidanceFailed}
          />

          {/* A rating per milestone: the first real signal about plans (B6). */}
          <MilestoneRating pathId={payload?.id} milestoneId={milestone.id} />
        </div>

        {/* Tools Section (the tour points at it: data-tour) */}
        <div className="bg-white rounded-2xl border border-slate-200 p-6 md:p-8 shadow-sm" data-tour="milestone-tools">
          <NormsPrompt />
          <MilestoneTools
            milestoneId={milestone.id}
            milestoneName={milestone.name}
            baseTools={milestone.tools || []}
            initialEdits={(payload as any)?.toolEdits?.[milestone.id]}
            third={<SponsoredService text={[milestone.name, milestone.race, milestone.description].filter(Boolean).join(' ')} />}
          />

          {/* Actions */}
          <div className="mt-8 pt-6 border-t border-slate-200 flex flex-wrap gap-4">
            <Link
              href={`/reflection?contextType=milestone&contextId=${milestoneId}`}
              className="inline-flex items-center gap-2 bg-slate-900 text-white px-6 py-3 rounded-xl hover:bg-slate-800 transition-colors font-medium"
            >
              <BookOpen className="h-5 w-5" />
              Journal / Reflection
            </Link>
            <Link
              href="/calendar"
              className="inline-flex items-center gap-2 bg-slate-100 text-slate-700 px-6 py-3 rounded-xl hover:bg-slate-200 transition-colors font-medium"
            >
              Calendar View
              <ChevronRight className="h-5 w-5" />
            </Link>
            <Link
              href="/pit-stop"
              className="inline-flex items-center gap-2 bg-cyan-50 text-cyan-700 px-6 py-3 rounded-xl hover:bg-cyan-100 transition-colors font-medium"
            >
              <Wrench className="h-5 w-5" />
              Pit Stop
            </Link>
          </div>
        </div>
      </div>
      </div>
    </div>
  )
}
