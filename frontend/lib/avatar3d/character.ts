export interface Character3D {
  v: 1
  /** Skin tone, '#rrggbb'. */
  skin: string
  /** Eye colour id (EYES). */
  eyes: string
  /** Hairstyle id (HAIRS) or 'none'. */
  hair: string
  hairColor: string
  /** Eyebrow shape id (BROWS) or 'none'. */
  brows: string
  /** Eyebrows and facial hair. */
  browColor: string
  /** Facial hair id (BEARDS) or 'none'. */
  beard: string
  /** 'natural' (the skin's own) or '#rrggbb'. */
  lips: string
  /** Facial features shown (FEATURES ids). */
  features: string[]
  /** Face paint id (FACE_PAINTS) or 'none'. */
  facePaint: string
  facePaintColor: string
  /** Tattoo id (TATTOOS) or 'none'. */
  tattoo: string
  tattooColor: string
  /** Glasses id (GLASSES) or 'none'. */
  glasses: string
  /** Outfit id (OUTFITS). */
  outfit: string
  /** What's worn: the outfit, or Basics (a plain tee and shorts). */
  attire: 'outfit' | 'basics'
  /** Face sliders, -1..1 (0 is MakeHuman's average). */
  face: Record<string, number>
  /** Body sliders, -1..1. */
  body: Record<string, number>
  /** Height, -1..1 (about 0.9x to 1.1x). */
  height: number
  smile: boolean
  pose: string
  environment: string
}

