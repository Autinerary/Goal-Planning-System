const HEX = /^#[0-9a-f]{6}$/
const hex = (v: unknown, fallback: string) => (typeof v === 'string' && HEX.test(v.toLowerCase()) ? v.toLowerCase() : fallback)
const oneOf = (v: unknown, list: readonly { id: string }[], fallback: string, extra: string[] = []) =>
  typeof v === 'string' && (extra.includes(v) || list.some((x) => x.id === v)) ? v : fallback
const clamp = (v: unknown) => {
  const n = typeof v === 'number' ? v : Number(v)
  return Number.isFinite(n) ? Math.max(-1, Math.min(1, Math.round(n * 100) / 100)) : 0
}
const sliders = (v: unknown, list: readonly { id: string; twoWay?: boolean }[]) => {
  const out: Record<string, number> = {}
  if (!v || typeof v !== 'object') return out
  for (const s of list) {
    const n = clamp((v as Record<string, unknown>)[s.id])
    const ok = s.twoWay === false ? Math.max(0, n) : n
    if (ok !== 0) out[s.id] = ok
  }
  return out
}

/** A saved (or any) value as a valid character: unknown parts fall back to the default's. */
export function sanitize(input: unknown): Character3D {
  const d = DEFAULT_CHARACTER
  const c = (input && typeof input === 'object' ? input : {}) as Record<string, unknown>
  const features = Array.isArray(c.features)
    ? FEATURES.map((f) => f.id as string).filter((id) => (c.features as unknown[]).includes(id))
    : []
  return {
    v: 1,
    skin: hex(c.skin, d.skin),
    eyes: oneOf(c.eyes, EYES, d.eyes),
    hair: oneOf(c.hair, HAIRS, d.hair, ['none']),
    hairColor: hex(c.hairColor, d.hairColor),
    brows: oneOf(c.brows, BROWS, d.brows, ['none']),
    browColor: hex(c.browColor, d.browColor),
    beard: oneOf(c.beard, BEARDS, d.beard, ['none']),
    lips: c.lips === 'natural' ? 'natural' : hex(c.lips, d.lips),
    features,
    facePaint: oneOf(c.facePaint, FACE_PAINTS, d.facePaint, ['none']),
    facePaintColor: hex(c.facePaintColor, d.facePaintColor),
    tattoo: oneOf(c.tattoo, TATTOOS, d.tattoo, ['none']),
    tattooColor: hex(c.tattooColor, d.tattooColor),
    glasses: oneOf(c.glasses, GLASSES, d.glasses, ['none']),
    outfit: oneOf(c.outfit, OUTFITS, d.outfit),
    attire: c.attire === 'basics' ? 'basics' : 'outfit',
    face: sliders(c.face, FACE_SLIDERS),
    body: sliders(c.body, BODY_SLIDERS),
    height: clamp(c.height),
    smile: c.smile === true,
    pose: oneOf(c.pose, POSES, d.pose),
    environment: oneOf(c.environment, ENVIRONMENTS, d.environment),
  }
}

const labelOf = (list: readonly { id: string; label: string }[], id: string) => list.find((x) => x.id === id)?.label || id
const nearest = (list: Swatch[], color: string) => {
  const rgb = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
  if (!HEX.test(color)) return color
  const [r, g, b] = rgb(color)
  let best = list[0]
  let bestD = Infinity
  for (const s of list) {
    if (!HEX.test(s.id)) continue
    const [r2, g2, b2] = rgb(s.id)
    const dist = (r - r2) ** 2 + (g - g2) ** 2 + (b - b2) ** 2
    if (dist < bestD) { bestD = dist; best = s }
  }
  return bestD === 0 ? best.label : `close to ${best.label.toLowerCase()}`
}
// Lower case at the start, but not "T-shirt" or a name in capitals.
const lower = (s: string) => (s.length > 1 && /[a-z ]/.test(s.charAt(1)) ? s.charAt(0).toLowerCase() + s.slice(1) : s)
const colourWords = (list: Swatch[], color: string) => {
  const n = nearest(list, color)
  return n.startsWith('close to') ? `a colour ${n}` : lower(n)
}
const listWords = (xs: string[]) => (xs.length < 2 ? xs.join('') : `${xs.slice(0, -1).join(', ')} and ${xs[xs.length - 1]}`)

/** One plain sentence describing the character, for screen readers and the page's text alternative. */
export function describe(c: Character3D): string {
  const parts: string[] = []
  parts.push(`skin ${lower(nearest(SKIN_TONES, c.skin))}`)
  parts.push(`${lower(labelOf(EYES, c.eyes))} eyes`)
  parts.push(c.hair === 'none' ? 'no hair' : `${lower(labelOf(HAIRS, c.hair))} hair in ${colourWords(HAIR_COLORS, c.hairColor)}`)
  parts.push(c.brows === 'none' ? 'no eyebrows' : `${lower(labelOf(BROWS, c.brows))} eyebrows`)
  if (c.beard !== 'none') parts.push(`a ${lower(labelOf(BEARDS, c.beard))}`)
  if (c.lips !== 'natural') parts.push(`${lower(nearest(LIP_COLORS, c.lips))} lips`)
  if (c.features.length) parts.push(listWords(c.features.map((f) => lower(labelOf(FEATURES, f)))))
  if (c.facePaint !== 'none') parts.push(`${lower(labelOf(FACE_PAINTS, c.facePaint))} face paint in ${colourWords(PAINT_COLORS, c.facePaintColor)}`)
  if (c.tattoo !== 'none') parts.push(`a ${lower(labelOf(TATTOOS, c.tattoo))} tattoo`)
  if (c.glasses !== 'none') parts.push(`${lower(labelOf(GLASSES, c.glasses))} glasses`)
  if (c.smile) parts.push('a smile')
  const outfit = c.attire === 'basics' ? 'Basics (a plain tee and shorts)' : labelOf(OUTFITS, c.outfit)
  return `Your character: ${listWords(parts)}. Outfit: ${outfit}. Pose: ${lower(labelOf(POSES, c.pose))}. Backdrop: ${lower(labelOf(ENVIRONMENTS, c.environment))}.`
}

/** How far each slider has moved, as words ("a little", "a lot"), for its spoken value. */
export function sliderWords(value: number, downLabel: string, upLabel: string): string {
  const a = Math.abs(value)
  if (a < 0.05) return 'Middle'
  const how = a < 0.35 ? 'A little' : a < 0.75 ? 'Quite a bit' : 'A lot'
  return `${how} ${lower(value < 0 ? downLabel : upLabel)}`
}
